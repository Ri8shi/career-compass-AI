/* ═══════════════════════════════════════════════════════════════
   export.js — PDF download & Markdown copy
   ═══════════════════════════════════════════════════════════════ */

const ExportManager = (() => {
  let _analysisData = null;
  let _meta = null;

  function init(data, meta) {
    _analysisData = data;
    _meta = meta;

    document.getElementById('btnExportPdf')?.addEventListener('click', exportPdf);
    document.getElementById('btnCopyRoadmap')?.addEventListener('click', copyRoadmap);
  }

  /** Export the dashboard as a printable PDF (browser print dialog). */
  function exportPdf() {
    window.print();
  }

  /** Copy the roadmap as Markdown to clipboard. */
  async function copyRoadmap() {
    if (!_analysisData?.roadmap) return;

    const lines = [
      `# Learning Roadmap — ${_meta?.targetRole || 'Target Role'}`,
      `> Generated by Career Compass AI on ${new Date().toLocaleDateString()}`,
      '',
    ];

    _analysisData.roadmap.forEach((phase) => {
      lines.push(`## Phase ${phase.phase}: ${phase.title}`);
      lines.push(`**Duration:** ${phase.duration || 'TBD'}`);
      lines.push('');

      if (phase.skills?.length) {
        lines.push('**Skills:**');
        phase.skills.forEach((s) => lines.push(`- ${s}`));
        lines.push('');
      }

      if (phase.resources?.length) {
        lines.push('**Resources:**');
        phase.resources.forEach((r) => {
          const url = r.url ? ` — [Link](${r.url})` : '';
          lines.push(`- [${r.type?.toUpperCase() || 'RESOURCE'}] ${r.name || r} (${r.platform || ''})${url}`);
        });
        lines.push('');
      }

      lines.push('---');
      lines.push('');
    });

    const markdown = lines.join('\n');

    try {
      await navigator.clipboard.writeText(markdown);
      showCopyFeedback();
    } catch {
      // Fallback
      const ta = document.createElement('textarea');
      ta.value = markdown;
      document.body.appendChild(ta);
      ta.select();
      document.execCommand('copy');
      document.body.removeChild(ta);
      showCopyFeedback();
    }
  }

  function showCopyFeedback() {
    const btn = document.getElementById('btnCopyRoadmap');
    if (!btn) return;
    const originalHTML = btn.innerHTML;
    btn.innerHTML = '<i data-lucide="check"></i> Copied!';
    btn.style.color = '#10b981';
    lucide.createIcons();
    setTimeout(() => {
      btn.innerHTML = originalHTML;
      btn.style.color = '';
      lucide.createIcons();
    }, 2000);
  }

  return { init };
})();
